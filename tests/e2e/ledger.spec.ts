import { expect, test } from '@playwright/test'

test('signed-in ledger edits, tab sync, and PWA offline cache', async ({ page, context }) => {
  test.setTimeout(60_000)
  await page.goto('/')
  await page.getByRole('button', { name: '테스트 계정으로 로그인' }).click()
  await expect(page.getByRole('heading', { name: '대시보드' })).toBeVisible()
  await expect(page.getByText('구독 A', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '거래', exact: true }).click()
  await expect(page.getByText('표시할 거래가 없습니다.')).toBeVisible()
  const other = await context.newPage()
  await other.goto('/transactions')
  await expect(other.getByText('표시할 거래가 없습니다.')).toBeVisible()

  await page.getByRole('button', { name: '거래 추가' }).click()
  await page.getByLabel('거래명').fill('테스트 점심')
  await page.getByRole('button', { name: '5,000원' }).click()
  await page.getByRole('button', { name: '저장', exact: true }).click()
  const row = other.getByRole('listitem').filter({ hasText: '테스트 점심' })
  await expect(row).toContainText('5,000원')
  await row.getByRole('button', { name: '수정' }).click()
  await other.getByRole('button', { name: '10,000원' }).click()
  await other.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByRole('listitem').filter({ hasText: '테스트 점심' })).toContainText('10,000원')

  await page.getByRole('link', { name: '설정' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '개인 기기에 오프라인 저장 켜기' }).click()
  await expect(page.getByRole('button', { name: '오프라인 저장 끄기' })).toBeVisible()
  await page.getByRole('link', { name: '거래' }).click()
  await expect(page.getByText('동기화 완료')).toBeVisible()
  await expect(page.getByText('테스트 점심')).toBeVisible()
  const controlled = await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    return !!navigator.serviceWorker.controller
  })
  expect(controlled).toBeTruthy()
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByText('테스트 점심')).toBeVisible()
  await expect(page.getByText('오프라인 또는 연결 중')).toBeVisible()
  await page.getByRole('button', { name: '수정' }).click()
  await page.getByRole('button', { name: '1,000원' }).click()
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByText(/서버 반영 대기 중입니다/)).toBeVisible()
  await context.setOffline(false)
  await expect(other.getByRole('listitem').filter({ hasText: '테스트 점심' })).toContainText('1,000원', { timeout: 20_000 })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '삭제' }).click()
  await expect(other.getByText('테스트 점심')).toHaveCount(0)
  await page.getByRole('link', { name: '설정' }).click()
  await page.getByRole('button', { name: '로그아웃' }).click()
  await expect(other.getByRole('button', { name: 'Google로 로그인' })).toBeVisible()
})
